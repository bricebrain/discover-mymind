import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync } from 'node:fs';
// Les validateurs générés doivent fonctionner sans eval et sans runtime CommonJS.
const ajv = new Ajv({ code: { source: true, esm: true, optimize: true }, strict: false });
for (const name of ['manifest', 'segments']) {
  const schema = JSON.parse(readFileSync(new URL(`../../contracts/${name}.schema.json`, import.meta.url)));
  const validate = ajv.compile(schema);
  writeFileSync(new URL(`../src/publications/${name}.generated.js`, import.meta.url), '// Generated by npm run contracts:generate. Do not edit.\n' + standaloneCode(ajv, validate).replace(/const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\).default;/g, 'const $1 = (text) => { let count = 0; for (const character of text) count++; return count; };'));
  writeFileSync(new URL(`../src/publications/${name}.generated.d.ts`, import.meta.url), 'declare const validate: { (value: unknown): boolean; errors?: { instancePath: string; message?: string }[] | null };\nexport default validate;\n');
}
